/**
 * Scans public/images/gallery category folders and generates src/data/eventGallery.ts
 */
import { readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const galleryRoot = join(__dirname, '..', 'public', 'images', 'gallery');
const outputPath = join(__dirname, '..', 'src', 'data', 'eventGallery.ts');

const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif']);
const VIDEO_EXT = new Set(['.mp4', '.webm', '.mov']);

/** Folder name on disk → category slug */
const CATEGORY_FOLDERS = [
  { folder: 'Wedding catering', category: 'weddings', displayName: 'Wedding Celebrations' },
  { folder: 'Birthday and other celebrations', category: 'celebrations', displayName: 'Celebrations & Special Occasions' },
  { folder: 'private gathering', category: 'private-gatherings', displayName: 'Private Gatherings' },
  { folder: 'food and set up', category: 'food-setups', displayName: 'Food & Catering Setups' },
  { folder: 'School catering', category: 'school-events', displayName: 'School & Institutional Events' },
  { folder: 'Our team', category: 'team', displayName: 'The Khidmat Team' },
];

function publicPath(folder, filename) {
  return `/images/gallery/${encodeURIComponent(folder)}/${encodeURIComponent(filename)}`;
}

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 48);
}

function buildAlt(categoryDisplayName, filename, index) {
  const base = categoryDisplayName.replace(/&/g, 'and');
  return `Khidmat ${base} — photograph ${index + 1}`;
}

function buildVideoAlt(categoryDisplayName, filename, index) {
  const base = categoryDisplayName.replace(/&/g, 'and');
  return `Khidmat ${base} — video ${index + 1}`;
}

const items = [];

for (const { folder, category, displayName } of CATEGORY_FOLDERS) {
  const folderPath = join(galleryRoot, folder);
  let files;

  try {
    files = await readdir(folderPath);
  } catch {
    console.warn(`Skipping missing folder: ${folder}`);
    continue;
  }

  const supported = files
    .filter((file) => {
      const ext = file.slice(file.lastIndexOf('.')).toLowerCase();
      return IMAGE_EXT.has(ext) || VIDEO_EXT.has(ext);
    })
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

  let imageIndex = 0;
  let videoIndex = 0;

  for (const file of supported) {
    const ext = file.slice(file.lastIndexOf('.')).toLowerCase();
    const isVideo = VIDEO_EXT.has(ext);
    const index = isVideo ? videoIndex++ : imageIndex++;
    const id = `${category}-${slugify(file.replace(ext, ''))}`;

    items.push({
      id,
      src: publicPath(folder, file),
      type: isVideo ? 'video' : 'image',
      category,
      alt: isVideo ? buildVideoAlt(displayName, file, index) : buildAlt(displayName, file, index),
      caption: displayName,
      title: displayName,
    });
  }

  console.log(`  ${folder}: ${supported.length} file(s)`);
}

const fileContents = `/**
 * Auto-generated by scripts/generate-event-gallery.mjs — do not edit manually.
 * Re-run: npm run generate:gallery
 */
export const eventGalleryItems = ${JSON.stringify(items, null, 2)};
`;

await writeFile(outputPath, fileContents, 'utf8');
console.log(`Generated ${items.length} gallery items → src/data/eventGallery.ts`);
